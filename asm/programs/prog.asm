; =============================================================================
; R128 Demo Program
;
; Демонстрация основных возможностей учебного процессора R128:
;   - арифметика и логика (ADD, SUB, AND, OR, XOR, NOT, SHL, SHR)
;   - сравнение и условные переходы (CMP, JE/JNE, JUGT, JSLT)
;   - работа с памятью (LOAD / STORE)
;   - сегментные регистры (MOVS, MFS, LOADS, STORES)
;   - дальний переход (JMPF)
;   - ввод-вывод (IN / OUT)
;   - HALT
;
; Результаты выводятся в I/O-порты:
;   порт 0  — вход (по умолчанию 0, в примере запускали с 10)
;   порт 1  — r1 + r1
;   порт 2  — (r1+r1) XOR ~r1
;   порт 3  — (r1+r1) << 4
;   порт 4  — значение из памяти (0xDEAD)
;   порт 5  — значение DS после MOVS (0x0010)
;   порт 6  — значение, прочитанное через LOADS (0xAA)
;   порт 7  — код успеха 0x5238 («R128»)
;
; Примечание о сегментах:
;   После демонстрации DS сегмент возвращается в 0, иначе все последующие
;   обычные LOAD/STORE обращаются к phys = DS*16 + offset и читают чужие данные.
;   ES явно инициализируется перед LOADS/STORES.
;
; Ассемблирование:
;   python3 asm/asm.py asm/programs/prog.asm -o asm/programs/prog.bin --listing asm/programs/prog.lst
;
; Запуск (порт 0 вернёт 10, память отвечает с задержкой 1 такт):
;   ./out/r128_runner asm/programs/prog.bin --input 10 --latency 1
; Успех: на порт 7 выводится 0x5238.
; =============================================================================

.org 0x0000

; -----------------------------------------------------------------------------
; 1. Ввод и простая арифметика / логика / сдвиги
; -----------------------------------------------------------------------------
_start:
        in      r1, 0               ; r1 ← порт 0

        add     r2, r1, r1          ; r2 = r1 + r1
        out     r2, 1               ; порт 1 ← 2·r1

        not     r3, r1              ; r3 = ~r1
        xor     r4, r2, r3          ; r4 = (r1+r1) XOR ~r1
        out     r4, 2               ; порт 2

        load    r6, r0, const_four  ; r6 = 4
        shl     r5, r2, r6          ; r5 = (r1+r1) << 4
        out     r5, 3               ; порт 3

; -----------------------------------------------------------------------------
; 2. Работа с памятью (LOAD / STORE), DS ещё равен 0
; -----------------------------------------------------------------------------
        load    r7, r0, magic       ; r7 = 0xDEAD
        store   r7, r0, buffer      ; buffer ← 0xDEAD
        load    r8, r0, buffer      ; r8 = buffer
        out     r8, 4               ; порт 4 ← 0xDEAD

; -----------------------------------------------------------------------------
; 3. Сравнение и условные переходы
; -----------------------------------------------------------------------------
        cmp     r8, r7
        je      equal_ok
        jmp     fail

equal_ok:
        mov     r9, r1
        add     r9, r9, r1          ; r9 = 2·r1
        cmp     r9, r2
        jne     fail

        ; беззнаковое: 5 > 3 ?
        load    r10, r0, const_five
        load    r11, r0, const_three
        cmp     r10, r11
        jugt    unsigned_ok
        jmp     fail

unsigned_ok:
        ; знаковое: -1 < 0 ?
        load    r12, r0, const_m1
        cmp     r12, r0
        jslt    signed_ok
        jmp     fail

signed_ok:

; -----------------------------------------------------------------------------
; 4. Сегментные регистры
; -----------------------------------------------------------------------------
        ; --- показ DS ---
        load    r13, r0, seg_val    ; r13 = 0x0010
        movs    ds, r13             ; DS ← 0x0010
        mfs     r14, ds             ; r14 ← DS
        out     r14, 5              ; порт 5 ← 0x0010

        ; ВАЖНО: возвращаем DS в 0, иначе дальнейшие load по меткам
        ; будут адресоваться как DS*16 + offset и попадут мимо образа.
        movs    ds, r0              ; DS ← 0

        ; --- LOADS / STORES через ES ---
        ; ES явно ставим в 0, offset = адрес buffer (внутри образа).
        movs    es, r0              ; ES ← 0
        load    r15, r0, const_aa   ; r15 = 0xAA
        stores  es, r0, r15, buffer ; ES:buffer ← 0xAA
        loads   r16, r0, es, buffer ; r16 ← ES:buffer
        out     r16, 6              ; порт 6 ← 0xAA

; -----------------------------------------------------------------------------
; 5. Дальний переход и код успеха
; -----------------------------------------------------------------------------
        jmpf    0, far_target       ; CS=0, PC=far_target

fail:
        load    r20, r0, code_fail
        out     r20, 7
        halt

far_target:
        load    r21, r0, code_ok
        out     r21, 7              ; порт 7 ← 0x5238
        halt

; =============================================================================
; Секция данных
; =============================================================================
        .align  16

magic:
        .word128 0xDEAD

buffer:
        .word128 0

const_four:
        .word128 4

const_five:
        .word128 5

const_three:
        .word128 3

const_m1:
        .word128 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF   ; -1

seg_val:
        .word128 0x0010

const_aa:
        .word128 0xAA

code_ok:
        .word128 0x00005238         ; «R128»

code_fail:
        .word128 0xDEAD0001
