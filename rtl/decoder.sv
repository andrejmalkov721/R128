`default_nettype none
/*------------------------------------------------------------------------------
 * R128 — декодер фиксированной 128-битной инструкции
 *
 * Назначение:
 *   Разбивает входное слово инструкции на поля без проверки допустимости
 *   opcode и без формирования управляющих сигналов.
 *
 * Формат:
 *   [127:112] opcode  — код операции;
 *   [111:106] rd      — регистр назначения / поле назначения;
 *   [105:100] rs1     — первый исходный регистр;
 *   [ 99: 94] rs2     — второй исходный регистр;
 *   [ 93:  0] imm     — непосредственное поле шириной 94 бита.
 *
 * Блок полностью комбинационный.
 *----------------------------------------------------------------------------*/
module decoder (
    input  logic [127:0] instruction, // полное 128-битное слово инструкции

    // Поля инструкции. Декодер не меняет значения и не интерпретирует их.
    output logic [15:0]  opcode, // код операции
    output logic [5:0]   rd,     // регистр назначения
    output logic [5:0]   rs1,    // первый источник
    output logic [5:0]   rs2,    // второй источник
    output logic [93:0]  imm     // непосредственный операнд / служебные поля
);

    // Выделение полей выполняется простыми срезами; дополнительной логики
    // декодирования здесь нет, поэтому задержка блока минимальна.
    assign opcode = instruction[127:112];
    assign rd     = instruction[111:106];
    assign rs1    = instruction[105:100];
    assign rs2    = instruction[99:94];
    assign imm    = instruction[93:0];

endmodule

`default_nettype wire
