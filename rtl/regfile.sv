`default_nettype none
/*------------------------------------------------------------------------------
 * R128 — файл регистров общего назначения (GPR)
 *
 * Организация:
 *   64 регистра по 128 бит; два асинхронных порта чтения и один синхронный
 *   порт записи. Адрес регистра задаётся 6-битным индексом.
 *
 * Архитектурное правило:
 *   R0 всегда равен нулю. Запись по адресу 0 игнорируется, чтение адреса 0
 *   возвращает 128'b0 независимо от содержимого массива.
 *
 * Сброс:
 *   Аппаратный сброс не очищает весь массив GPR (кроме принудительного
 *   удержания R0 = 0). Программная инициализация выполняется загрузчиком/ПО.
 *   Для удобства симуляции массив инициализируется нулями через initial.
 *
 * Важно: write-through отсутствует. Чтение в том же такте, что и запись
 * по тому же адресу, возвращает старое значение. Потребитель (ID/EX)
 * обязан выполнять bypass/forwarding самостоятельно.
 *----------------------------------------------------------------------------*/
module regfile (
    input  logic         clk,  
    input  logic         rst,    

    // Банк r: 64 × 128 бит
    input  logic         r_we,     
    input  logic [5:0]   r_waddr,  
    input  logic [127:0] r_wdata,   

    input  logic [5:0]   r_raddr_1,  
    input  logic [5:0]   r_raddr_2,

    output logic [127:0] r_rdata_1,
    output logic [127:0] r_rdata_2
);

    // Физический массив GPR. Атрибут запрещает инструменту пытаться
    // представить этот небольшой банк как обычную блочную RAM.
    (* ram_style = "registers" *)
    logic [127:0] r [0:63];

    // Для чистой симуляции инициализируем массив нулями.
    // Обёрнуто в `ifndef SYNTHESIS`, чтобы ASIC-синтезаторы
    // не выдавали предупреждения о initial для больших массивов.
    // Архитектурно полный аппаратный reset GPR не выполняется —
    // инициализация возлагается на ПО/загрузчик.
`ifndef SYNTHESIS
    initial begin
        for (int i = 0; i < 64; i++)
            r[i] = 128'd0;
    end
`endif

    // Reset не очищает массив GPR: это исключает сброс 8192 бит
    // регистрового файла и соответствует аппаратной реализации.
    // R0 принудительно удерживается равным нулю.
    always_ff @(posedge clk) begin
        if (!rst && r_we && (r_waddr != 6'd0))
            r[r_waddr] <= r_wdata;

        r[0] <= 128'd0;
    end

    // Асинхронное чтение. Изменение адреса сразу меняет данные на выходе;
    // отдельная обработка R0 сохраняет архитектурное правило нулевого регистра.
    assign r_rdata_1 =
        (r_raddr_1 == 6'd0) ? 128'd0 : r[r_raddr_1];

    assign r_rdata_2 =
        (r_raddr_2 == 6'd0) ? 128'd0 : r[r_raddr_2];

endmodule

`default_nettype wire
